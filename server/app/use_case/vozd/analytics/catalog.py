_ROMAN = {"IV": "4", "III": "3", "II": "2", "I": "1"}
_ROMAN_RE = __import__("re").compile(r"^(IV|III|II|I)\.(\d+)$")


def normalize_id(metric_id: str) -> str:
    """Идентификатор метрики: «2.28». Старая запись с римским номером раздела («II.28») тоже принимается."""
    m = _ROMAN_RE.match((metric_id or "").strip())
    return f"{_ROMAN[m.group(1)]}.{m.group(2)}" if m else (metric_id or "").strip()


def normalize_section(section: str) -> str:
    sec = (section or "").strip().upper()
    return _ROMAN.get(sec, sec)


